  const languages = Object.freeze(['en', 'zh']);
  let currentLanguage = 'en';

  function assertCompleteCatalog() {
    const referenceKeys = Object.keys(messages.en).sort();
    for (const language of languages) {
      const keys = Object.keys(messages[language]).sort();
      if (keys.length !== referenceKeys.length || keys.some((key, index) => key !== referenceKeys[index])) {
        throw new Error(`Incomplete i18n catalog for ${language}`);
      }
    }
  }

  function setLanguage(language) {
    if (!languages.includes(language)) throw new Error(`Unsupported language: ${language}`);
    currentLanguage = language;
  }

  function t(key, params = {}) {
    const template = messages[currentLanguage][key];
    if (template === undefined) throw new Error(`Missing i18n key: ${key}`);
    return template.replace(/\{(\w+)\}/g, (match, name) => {
      if (!(name in params)) throw new Error(`Missing i18n param ${name} for ${key}`);
      return String(params[name]);
    });
  }

  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(element => {
      element.textContent = t(element.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
      element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
    });
  }

  assertCompleteCatalog();

  window.I18n = Object.freeze({ languages, messages, setLanguage, t, apply, get language() { return currentLanguage; } });
